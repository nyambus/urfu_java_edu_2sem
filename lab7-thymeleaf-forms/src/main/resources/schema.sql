CREATE TABLE IF NOT EXISTS STUDENTS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(15),
    surname VARCHAR(25),
    faculty VARCHAR(20),
    age INTEGER
);

CREATE TABLE IF NOT EXISTS EDUCATIONAL_GROUPS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_number VARCHAR(20),
    faculty VARCHAR(20),
    course INTEGER
);
